#!/usr/bin/env python3
"""Generates src/unicode/tables.rs from the Unicode Character Database.

    python3 tools/gen_unicode.py ~/src/ucd

Data: Unicode License v3 (https://www.unicode.org/license.txt).
"""
import os
import sys

ucd = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser("~/src/ucd")


def ranges_from(fname, want):
    """Code point ranges whose property field equals `want`."""
    out = []
    for line in open(os.path.join(ucd, fname), encoding="utf-8"):
        line = line.split("#")[0].strip()
        if not line:
            continue
        cps, prop = [x.strip() for x in line.split(";")[:2]]
        if prop != want:
            continue
        if ".." in cps:
            a, b = cps.split("..")
            out.append((int(a, 16), int(b, 16)))
        else:
            out.append((int(cps, 16), int(cps, 16)))
    return merge(out)


def merge(rs):
    rs = sorted(rs)
    out = []
    for a, b in rs:
        if out and a <= out[-1][1] + 1:
            out[-1] = (out[-1][0], max(out[-1][1], b))
        else:
            out.append((a, b))
    return out


def version():
    first = open(os.path.join(ucd, "DerivedCoreProperties.txt"), encoding="utf-8").readline()
    return first.strip("# \n").split("-")[1].replace(".txt", "")


def emit(f, name, rs):
    f.write(f"pub static {name}: &[(u32, u32)] = &[\n")
    for i in range(0, len(rs), 4):
        f.write("    " + " ".join(f"(0x{a:X}, 0x{b:X})," for a, b in rs[i:i + 4]) + "\n")
    f.write("];\n\n")


tables = {
    "ID_START": ranges_from("DerivedCoreProperties.txt", "ID_Start"),
    "ID_CONTINUE": ranges_from("DerivedCoreProperties.txt", "ID_Continue"),
    "SPACE_SEPARATOR": ranges_from("DerivedGeneralCategory.txt", "Zs"),
}

with open("src/unicode/tables.rs", "w", encoding="utf-8") as f:
    f.write(f"//! Generated by tools/gen_unicode.py from the Unicode Character Database {version()}.\n")
    f.write("//! Data: Unicode License v3 (https://www.unicode.org/license.txt).\n\n")
    f.write(f"pub const UNICODE_VERSION: &str = \"{version()}\";\n\n")
    for k, v in tables.items():
        emit(f, k, v)
print("wrote src/unicode/tables.rs", {k: len(v) for k, v in tables.items()})
