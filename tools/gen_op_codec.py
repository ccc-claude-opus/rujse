#!/usr/bin/env python3
"""Generates src/op_codec.rs: byte encoding of `Op` and the field-less
enums of src/bytecode.rs, for the bytecode cache.

    python3 tools/gen_op_codec.py

Run it after changing `Op`; the cache version (`cache::VERSION`) must
change with it.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = (ROOT / "src/bytecode.rs").read_text()

TYPES = {"Reg": "u16", "K": "u32", "Label": "u32", "u8": "u8", "u16": "u16", "u32": "u32",
         "i32": "i32", "bool": "bool", "BinKind": "bin_kind"}


def enum_body(name):
    m = re.search(r"pub enum %s \{\n(.*?)\n\}" % name, SRC, re.S)
    lines = [l for l in m.group(1).split("\n") if not l.strip().startswith("//")]
    return "\n".join(lines)


def variants(name):
    """[(variant, kind, fields)] with kind None / 'tuple' / 'struct'."""
    out = []
    body = enum_body(name)
    for m in re.finditer(r"^    ([A-Z]\w*)(\s*\((.*?)\)|\s*\{(.*?)\})?,", body, re.M | re.S):
        v = m.group(1)
        if m.group(3) is not None:
            fields = [t.strip() for t in m.group(3).split(",") if t.strip()]
            out.append((v, "tuple", fields))
        elif m.group(4) is not None:
            fields = [tuple(x.strip() for x in f.split(":")) for f in m.group(4).split(",") if f.strip()]
            out.append((v, "struct", fields))
        else:
            out.append((v, None, []))
    return out


def unit_enum(name):
    vs = variants(name)
    assert all(k is None for _, k, _ in vs), name
    snake = re.sub(r"(?<!^)([A-Z])", r"_\1", name).lower()
    put = "\n".join(f"        {name}::{v} => {i}," for i, (v, _, _) in enumerate(vs))
    get = "\n".join(f"        {i} => {name}::{v}," for i, (v, _, _) in enumerate(vs))
    return f"""
pub fn {snake}_to_u8(v: {name}) -> u8 {{
    match v {{
{put}
    }}
}}

pub fn {snake}_from_u8(b: u8) -> Option<{name}> {{
    Some(match b {{
{get}
        _ => return None,
    }})
}}
"""


def main():
    ops = variants("Op")
    assert len(ops) < 256
    put, get = [], []
    for i, (v, kind, fields) in enumerate(ops):
        if kind is None:
            put.append(f"        Op::{v} => w.u8({i}),")
            get.append(f"        {i} => Op::{v},")
        elif kind == "tuple":
            names = [f"a{j}" for j in range(len(fields))]
            writes = " ".join(f"w.{TYPES[t]}({n});" for n, t in zip(names, fields))
            reads = ", ".join(f"r.{TYPES[t]}()?" for t in fields)
            put.append(f"        Op::{v}({', '.join(names)}) => {{ w.u8({i}); {writes} }}")
            get.append(f"        {i} => Op::{v}({reads}),")
        else:
            names = [n for n, _ in fields]
            writes = " ".join(f"w.{TYPES[t]}({n});" for n, t in fields)
            reads = ", ".join(f"{n}: r.{TYPES[t]}()?" for n, t in fields)
            put.append(f"        Op::{v} {{ {', '.join(names)} }} => {{ w.u8({i}); {writes} }}")
            get.append(f"        {i} => Op::{v} {{ {reads} }},")
    out = f"""//! Generated by tools/gen_op_codec.py from src/bytecode.rs: do not edit.

use crate::bytecode::{{BinKind, BindingKind, FuncKind, Op}};
use crate::cache::{{Reader, Writer}};

pub fn put_op(w: &mut Writer, op: Op) {{
    match op {{
{chr(10).join(put)}
    }}
}}

pub fn get_op(r: &mut Reader) -> Option<Op> {{
    Some(match r.u8()? {{
{chr(10).join(get)}
        _ => return None,
    }})
}}
{unit_enum("BinKind")}{unit_enum("FuncKind")}{unit_enum("BindingKind")}"""
    (ROOT / "src/op_codec.rs").write_text(out)


main()
