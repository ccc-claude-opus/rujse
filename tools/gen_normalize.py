#!/usr/bin/env python3
"""Generates src/unicode/normalize_tables.rs (String.prototype.normalize)
from the Unicode Character Database.

    python3 tools/gen_normalize.py ~/src/ucd

Tables: canonical combining classes, decomposition mappings (canonical
and compatibility, not applied recursively: the code does that) and the
canonical compositions (pairs whose composite is not excluded). Hangul
syllables are algorithmic and not in the tables.

Data: Unicode License v3 (https://www.unicode.org/license.txt).
"""
import os
import sys

ucd = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser("~/src/ucd")
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")

ccc = {}
decomp = {}  # cp -> (compat, [cps])
for line in open(os.path.join(ucd, "UnicodeData.txt"), encoding="utf-8"):
    f = line.rstrip("\n").split(";")
    cp = int(f[0], 16)
    if int(f[3]) != 0:
        ccc[cp] = int(f[3])
    d = f[5].strip()
    if d:
        compat = d.startswith("<")
        if compat:
            d = d.split(">", 1)[1].strip()
        decomp[cp] = (compat, [int(x, 16) for x in d.split()])

# Ranges in UnicodeData.txt (<..., First>/<..., Last>) have no ccc or
# decompositions, so single lines are enough.

excluded = set()
for line in open(os.path.join(ucd, "DerivedNormalizationProps.txt"), encoding="utf-8"):
    line = line.split("#")[0].strip()
    if not line:
        continue
    parts = [x.strip() for x in line.split(";")]
    if parts[1] != "Full_Composition_Exclusion":
        continue
    if ".." in parts[0]:
        a, b = parts[0].split("..")
        excluded.update(range(int(a, 16), int(b, 16) + 1))
    else:
        excluded.add(int(parts[0], 16))

compose = []
for cp, (compat, m) in decomp.items():
    if not compat and len(m) == 2 and cp not in excluded:
        compose.append((m[0], m[1], cp))
compose.sort()

data = []
entries = []
for cp in sorted(decomp):
    compat, m = decomp[cp]
    entries.append((cp, len(data), len(m), compat))
    data.extend(m)
assert len(data) < 65536

out = ["//! Generated by tools/gen_normalize.py from the Unicode Character",
       "//! Database (Unicode License v3): do not edit.", "",
       "/// (code point, canonical combining class), for classes other than 0.",
       "pub static CCC: &[(u32, u8)] = &["]
out += [f"    (0x{cp:X}, {c})," for cp, c in sorted(ccc.items())]
out += ["];", "",
        "/// (code point, start in DECOMP_DATA, length, compatibility mapping).",
        "pub static DECOMP: &[(u32, u16, u8, bool)] = &["]
out += [f"    (0x{cp:X}, {s}, {n}, {'true' if c else 'false'})," for cp, s, n, c in entries]
out += ["];", "", "pub static DECOMP_DATA: &[u32] = &["]
for i in range(0, len(data), 12):
    out.append("    " + " ".join(f"0x{x:X}," for x in data[i:i + 12]))
out += ["];", "", "/// (first, second, composite), sorted.", "pub static COMPOSE: &[(u32, u32, u32)] = &["]
out += [f"    (0x{a:X}, 0x{b:X}, 0x{c:X})," for a, b, c in compose]
out += ["];", ""]
open(os.path.join(root, "src/unicode/normalize_tables.rs"), "w").write("\n".join(out))
print(f"ccc {len(ccc)}, decompositions {len(entries)} ({len(data)} code points), compositions {len(compose)}")
